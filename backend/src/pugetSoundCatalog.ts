export function inferNearestCorridor(lat: number, lng: number): {
  corridor: PugetSoundCorridor;
  nearestLandmark: PugetSoundLandmark;
  distanceKm: number;
} {
  let best = PUGET_SOUND_LANDMARKS[0];
  let bestDist = Infinity;

  for (const landmark of PUGET_SOUND_LANDMARKS) {
    const dist = haversineDistanceKm(lat, lng, landmark.lat, landmark.lng);
    if (dist < bestDist) {
      bestDist = dist;
      best = landmark;
    }
  }

  return {
    corridor: best.corridor,
    nearestLandmark: best,
    distanceKm: bestDist,
  };
}

